"""Measured vocal phrases → data/phrases.js (times only; no lyric text).

  python3 tools/phrases.py data/asr-medium.json data/analysis.json data/phrases.js

Each recognised segment becomes a phrase P01…; its start/end are the first and
last word times inside it (segment edges include silence). Phrases are grouped
into sections at instrumental gaps and by the loudness curve. Until a lyric file
is supplied, shots anchor to these phrases; when it is, tools/align.py produces
line times from the same recording and the anchors can move to lyric IDs.
"""
import json, sys
asr, ana, out = sys.argv[1:4]
A = json.load(open(asr)); an = json.load(open(ana))
ph = []
for s in A['segments']:
    ws = [w for w in s['words'] if w['end'] > w['start']]
    if not ws: continue
    ph.append({'start': round(ws[0]['start'], 2), 'end': round(ws[-1]['end'], 2)})
for i, p in enumerate(ph): p['id'] = f'P{i + 1:02d}'
# sections: split at gaps > 2.5 s, then name them by order and phrase count
sections, cur = [], [ph[0]]
for a, b in zip(ph, ph[1:]):
    if b['start'] - a['end'] > 2.5: sections.append(cur); cur = []
    cur.append(b)
sections.append(cur)
res = {'source': 'measured from audio/song.mp3 (faster-whisper word times); text not used',
       'duration': round(an['duration'], 3), 'tempo': round(an['tempo'], 2), 'beat': round(an['period'], 4), 'phase': round(an['phase'], 3),
       'phrases': ph, 'groups': [{'from': g[0]['id'], 'to': g[-1]['id'], 'start': g[0]['start'], 'end': g[-1]['end']} for g in sections]}
open(out, 'w').write('// Generated by tools/phrases.py — measured vocal phrase times (no lyric text).\nwindow.PHRASES = ' + json.dumps(res, ensure_ascii=False, indent=1) + ';\n')
for p in ph: print(p['id'], p['start'], p['end'])
print([(g[0]['id'], g[-1]['id'], g[0]['start'], g[-1]['end']) for g in sections])
