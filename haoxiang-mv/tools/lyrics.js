// Converts the song's lyric file into data/lyrics.js for the renderer.
//
//   node tools/lyrics.js path/to/song.lrc [--offset 0.0]   (LRC, optionally enhanced with <mm:ss.xx> word tags)
//   node tools/lyrics.js path/to/song.srt                  (SRT)
//
// Lyrics are only ever read from the file you give it. Line IDs (L01, L02, …)
// follow the file's order and are what data/storyboard.js refers to.
const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : d; };
const out = path.join(__dirname, '..', 'data', 'lyrics.js');
const ts = (m, s) => parseInt(m, 10) * 60 + parseFloat(s);

function parseLRC(src, offset) {
  const lines = [];
  let fileOffset = 0;
  for (const raw of src.split(/\r?\n/)) {
    const off = raw.match(/^\[offset:\s*([+-]?\d+)\]/i);
    if (off) { fileOffset = parseInt(off[1], 10) / 1000; continue; }
    const stamps = [...raw.matchAll(/\[(\d+):(\d+(?:\.\d+)?)\]/g)];
    if (!stamps.length) continue;
    let body = raw.replace(/\[(\d+):(\d+(?:\.\d+)?)\]/g, '');
    // enhanced LRC word timing: <mm:ss.xx>字
    const words = [];
    const wordRe = /<(\d+):(\d+(?:\.\d+)?)>([^<]*)/g;
    let m, plain = '';
    if (/<\d+:\d+/.test(body)) {
      while ((m = wordRe.exec(body))) { for (const ch of m[3]) { words.push({ t: ts(m[1], m[2]) + offset + fileOffset, ch }); } plain += m[3]; }
      body = plain;
    }
    const text = body.trim();
    // an empty timed line marks where the previous phrase ends (instrumental gap)
    for (const s of stamps) lines.push({ start: ts(s[1], s[2]) + offset + fileOffset, text, words: words.length ? words.filter(w => w.ch.trim()) : undefined });
  }
  lines.sort((a, b) => a.start - b.start);
  for (let i = 1; i < lines.length; i++) if (!lines[i].text && lines[i - 1].text && lines[i - 1].end === undefined) lines[i - 1].end = lines[i].start;
  return lines.filter(l => l.text);
}
function parseSRT(src, offset) {
  const lines = [];
  for (const block of src.split(/\r?\n\r?\n/)) {
    const m = block.match(/(\d+):(\d+):(\d+)[,.](\d+)\s*-->\s*(\d+):(\d+):(\d+)[,.](\d+)\s*\n([\s\S]+)/);
    if (!m) continue;
    const t = (h, mi, s, ms) => +h * 3600 + +mi * 60 + +s + +ms / 1000;
    lines.push({ start: t(m[1], m[2], m[3], m[4]) + offset, end: t(m[5], m[6], m[7], m[8]) + offset, text: m[9].trim().replace(/\s*\n\s*/g, ' ') });
  }
  return lines;
}

let data;
{
  const file = args.find(a => !a.startsWith('--') && a !== opt('offset'));
  if (!file) { console.error('usage: node tools/lyrics.js <song.lrc|song.srt> [--offset s]'); process.exit(1); }
  const src = fs.readFileSync(file, 'utf8'), offset = parseFloat(opt('offset', '0'));
  const lines = /\.srt$/i.test(file) ? parseSRT(src, offset) : parseLRC(src, offset);
  for (let i = 0; i < lines.length; i++) if (lines[i].end === undefined) lines[i].end = i + 1 < lines.length ? lines[i + 1].start - 0.05 : lines[i].start + 4;
  data = { placeholder: false, source: path.basename(file), wordTiming: lines.some(l => l.words), lines };
}
data.lines.forEach((l, i) => { l.id = 'L' + String(i + 1).padStart(2, '0'); });
fs.writeFileSync(out, '// generated by tools/lyrics.js — do not edit by hand\nwindow.LYRICS = ' + JSON.stringify(data, null, 1) + ';\n');
const chars = new Set(data.lines.map(l => l.text).join(''));
console.log(`${data.lines.length} lines → ${path.relative(process.cwd(), out)} (${data.wordTiming ? 'word timing' : 'line timing'}, ${chars.size} distinct characters)`);
